def compute_class_weight_dictionary(y_train):
    # Helper for returning a dictionary instead of an array
    classes = np.unique(y_train)
    class_weights = compute_class_weight(class_weight="balanced", classes=classes, y=y_train)
    class_weight_dict = dict(zip(classes, class_weights))
    return class_weight_dict

def classify(vectors, labels, type="DT"):
    # Random Splitting With Ratio 3:1
    train_vectors, test_vectors, train_labels, test_labels = train_test_split(
        vectors, labels, stratify=labels, test_size=0.25, random_state=42
    )

    # Compute class weights for imbalance handling
    class_weights = compute_class_weight_dictionary(train_labels)
    print(f"Class Weights: {class_weights}")

    # Initialize Model
    classifier = None
    if type == "MNB":
        print("\nBuilding Multinomial Naive Bayes (MNB) Model...")
        classifier = MultinomialNB()

        # Grid Search for hyperparameter tuning
        param_grid = {'alpha': [0.1, 0.2, 0.5, 0.7, 1.0, 2.0, 5.0]}
        grid_search = GridSearchCV(estimator=classifier, param_grid=param_grid, cv=5, scoring='accuracy', n_jobs=-1)
