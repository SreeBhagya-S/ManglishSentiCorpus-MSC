class TextDataset(Dataset):
    def __init__(self, data, labels, tokenizer, max_seq_length):
        self.data = data
        self.labels = labels
        self.tokenizer = tokenizer
        self.max_seq_length = max_seq_length

    def __len__(self):
        return len(self.data)

    def __getitem__(self, idx):
        text = self.data[idx]
        label = self.labels[idx]  # Get the corresponding label
        encoding = self.tokenizer.encode(text)
        tokens = encoding.ids[:self.max_seq_length]
        padded_tokens = tokens + [0] * (self.max_seq_length - len(tokens))
        return torch.tensor(padded_tokens), torch.tensor(label)  # Return both tokens and label

